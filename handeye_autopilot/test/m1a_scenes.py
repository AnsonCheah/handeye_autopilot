"""Scene builders for the M1a tests, driven by spec/m1a.yaml.

Run ``python3 test/m1a_scenes.py --write`` (from the package directory) to
regenerate the committed fixture images and their truth file.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import math
from pathlib import Path
import sys
from typing import Any

import cv2
import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from handeye_autopilot.core import cv_compat  # noqa: E402
from handeye_autopilot.core import transforms as tf  # noqa: E402
from handeye_autopilot.core.boards import BoardSpec, board_texture  # noqa: E402
from handeye_autopilot.core.camera import CameraModel  # noqa: E402
from handeye_autopilot.core.render import ImageEffects, PlanarObject, Renderer, look_at_board  # noqa: E402

SPEC = yaml.safe_load((HERE / 'spec' / 'm1a.yaml').read_text())
FIXTURE_DIR = HERE / 'fixtures' / 'm1a'
PX_PER_SQUARE = 60
MARGIN_PX = 30          # white paper around the grid, as on a real print


def camera(name: str) -> CameraModel:
    return CameraModel.from_dict(SPEC['cameras'][name])


def board(name: str) -> BoardSpec:
    return BoardSpec.from_dict(SPEC['boards'][name])


def board_centre(spec: BoardSpec) -> np.ndarray:
    w, h = spec.size_m
    return np.array([w / 2, h / 2, 0.0])


def pose(scene: dict[str, Any], spec: BoardSpec | None, cam: CameraModel,
         centre: np.ndarray | None = None) -> np.ndarray:
    tilt = scene.get('tilt', [0, 0])
    c = centre if centre is not None else board_centre(spec)  # type: ignore[arg-type]
    return look_at_board(c, scene['distance'], math.radians(tilt[0]), math.radians(tilt[1]),
                         math.radians(scene.get('roll', 0)),
                         offset_px=tuple(scene.get('offset', (0.0, 0.0))), camera=cam)


@dataclass
class Scene:
    camera: CameraModel
    board: BoardSpec
    camera_T_board: np.ndarray
    objects: list[PlanarObject]
    effects: ImageEffects

    def render(self, seed: int | None = None) -> np.ndarray:
        rng = np.random.default_rng(SPEC['seed'] if seed is None else seed)
        return Renderer(self.camera, self.effects).render(self.objects, rng)


def build(scene: dict[str, Any]) -> Scene:
    cam = camera(scene['camera'])
    spec = board(scene['board'])
    tex, H = board_texture(spec, PX_PER_SQUARE, MARGIN_PX)
    T = pose(scene, spec, cam)
    objects = [PlanarObject(tex, H, T)]
    if 'second_board' in scene:
        objects.append(PlanarObject(tex, H, pose(scene['second_board'], spec, cam)))
    for rect in scene.get('occluders', []):
        # A plain grey card 3 cm in front of the board, covering a board-frame rectangle.
        (x0, x1), (y0, y1) = rect['x'], rect['y']
        occ = np.full((10, 10), 200, np.uint8)
        H_occ = np.array([[10 / (x1 - x0), 0, -0.5], [0, 10 / (y1 - y0), -0.5], [0, 0, 1]])
        objects.append(PlanarObject(occ, H_occ, T @ tf.make(np.eye(3), [x0, y0, -0.03])))
    strays = scene.get('strays', [])
    if 'stray' in scene:
        strays = [scene['stray'], *strays]
    for st in strays:
        # A loose printed marker (6 cm card) with an ID that is also on the board.
        dictionary = cv_compat.get_dictionary(spec.dictionary)
        img = np.pad(cv_compat.marker_image(dictionary, st['id'], 120), 20,
                     constant_values=255)
        H_m = np.array([[160 / 0.06, 0, -0.5], [0, 160 / 0.06, -0.5], [0, 0, 1]])
        objects.append(PlanarObject(img, H_m,
                                    pose(st, None, cam, centre=np.array([0.03, 0.03, 0.0]))))
    fx = ImageEffects(noise_sigma=SPEC['noise_sigma'], blur_sigma=scene.get('blur_sigma', 0.0))
    return Scene(cam, spec, T, objects, fx)


def fixture_path(name: str) -> Path:
    return FIXTURE_DIR / f'{name}.png'


def truth() -> dict[str, Any]:
    return yaml.safe_load((FIXTURE_DIR / 'truth.yaml').read_text())


def write_fixtures() -> None:
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    out: dict[str, Any] = {'opencv_version': cv2.__version__, 'fixtures': {}}
    for name, scene in SPEC['fixtures'].items():
        s = build(scene)
        cv2.imwrite(str(fixture_path(name)), s.render())
        out['fixtures'][name] = {'camera_T_board': s.camera_T_board.tolist(),
                                 'expect': scene['expect']}
    (FIXTURE_DIR / 'truth.yaml').write_text(
        '# Generated by m1a_scenes.py --write; true board pose per fixture image.\n'
        + yaml.safe_dump(out, sort_keys=False))
    print(f'wrote {len(SPEC["fixtures"])} fixtures to {FIXTURE_DIR}')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true', help='regenerate the fixture images')
    if p.parse_args().write:
        write_fixtures()
