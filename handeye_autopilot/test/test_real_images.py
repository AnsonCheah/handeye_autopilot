"""Real photographs (OpenCV sample data) through detection and gates.

Expected outcomes: spec/real_opencv.yaml. Corner pixels found on OpenCV 4.6
are committed (fixtures/real_opencv/corners.yaml, regenerate with
``python3 test/test_real_images.py --write``); 4.10 and 4.12 must return the
same IDs and board coordinates and pixels within the committed tolerance.
"""

from pathlib import Path
import sys

import cv2
import numpy as np
import pytest
import yaml

from handeye_autopilot.core.boards import BoardSpec
from handeye_autopilot.core.camera import CameraModel
from handeye_autopilot.core.capture import Frame, process_frame
from handeye_autopilot.core.config import CaptureConfig

HERE = Path(__file__).resolve().parent
DIR = HERE / 'fixtures' / 'real_opencv'
SPEC = yaml.safe_load((HERE / 'spec' / 'real_opencv.yaml').read_text())
CORNERS = DIR / 'corners.yaml'
PIXEL_TOL = 0.05     # px, across OpenCV versions


def camera(name):
    fs = cv2.FileStorage(str(DIR / name), cv2.FILE_STORAGE_READ)
    K = fs.getNode('camera_matrix').mat()
    D = fs.getNode('distortion_coefficients').mat().ravel()
    w, h = int(fs.getNode('image_width').real()), int(fs.getNode('image_height').real())
    return CameraModel(K, D, w, h)


def run(name):
    item = SPEC['images'][name]
    img = cv2.imread(str(DIR / f'{name}.jpg'), cv2.IMREAD_GRAYSCALE)
    assert img is not None
    spec = BoardSpec.from_dict(SPEC['boards'][item['board']])
    return process_frame(Frame(img, 0.0, np.eye(4)), spec, camera(item['intrinsics']),
                         CaptureConfig())


@pytest.mark.parametrize('name', list(SPEC['images']))
def test_real_image_outcome(name):
    res = run(name)
    expect = SPEC['images'][name]['expect']
    got = 'accepted' if res.outcome.accepted else res.outcome.reject
    assert got == expect, res.outcome.detail
    if res.outcome.accepted:
        assert res.outcome.metrics['reprojection_rms_px'] <= SPEC['max_reprojection_rms_px']


@pytest.mark.parametrize('name', list(SPEC['images']))
def test_real_image_corners_match_across_opencv_versions(name):
    stored = yaml.safe_load(CORNERS.read_text())['images'].get(name)
    det = run(name).detection
    if stored is None:
        assert not det.ok or len(det.ids) == 0
        return
    np.testing.assert_array_equal(det.ids, stored['ids'])
    np.testing.assert_allclose(det.image_points, stored['image_points'], atol=PIXEL_TOL)


def write() -> None:
    out = {'opencv_version': cv2.__version__, 'images': {}}
    for name in SPEC['images']:
        det = run(name).detection
        if det.ok and len(det.ids):
            out['images'][name] = {'ids': det.ids.tolist(),
                                   'image_points': np.round(det.image_points, 4).tolist()}
    CORNERS.write_text('# Generated by test_real_images.py --write\n'
                       + yaml.safe_dump(out, sort_keys=False, default_flow_style=None))
    print(f'wrote {CORNERS}')


if __name__ == '__main__':
    sys.path.insert(0, str(HERE.parent))
    if '--write' in sys.argv:
        write()
